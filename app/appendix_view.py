"""
appendix_view.py -- the reviewer-facing Human Evidence Appendix, rendered on
request from a review's saved data.

The appendix stored when a review completes is kept unchanged as the original
record (it also lists every initial-reading observation, for audit). This
module builds a concise presentation of the same data for the reviewer:

  A. the final appraisal's concerns and verification questions, each with
     where evidence was located and any qualification;
  B. a one-paragraph summary of initial-reading observations that have no
     wording match in the final appraisal (the list stays in the original);
  C. what each evidence status does and does not establish.

Deterministic: no model is called and nothing is stored. It works for any
saved review that has its final appraisal; where Evidence Cards or the
observation record are missing, it says so rather than reconstructing them.
The output states that it is a presentation generated now, so it cannot be
mistaken for the stored original.
"""
from __future__ import annotations

from typing import Any, Dict, List, Optional, Sequence, Tuple

import decisions_report as dr
import evidence_cards as ec
import human_evidence_appendix as hea
import quote_match as qm
import reviewer_presentation as presentation

EXCERPT_CHARS = 400

PRESENTATION_NOTE = (
    "Presentation generated by the current application from this review's saved data{when}. "
    "No model was run. The appendix saved when the review was completed is unchanged and "
    "can be downloaded as the original appendix.")


def _qualifications(card: Optional[Dict[str, Any]]) -> List[str]:
    if not card:
        return []
    out = []
    if presentation.disputed(card):
        out.append("The AI verifier disputed this finding (a proposed correction or an objection). "
                   "Neither assessment has been established; see its Evidence Card.")
    if card.get("warnings"):
        out.append("The verification record contains a potential inconsistency; see its Evidence Card.")
    return out


def _location_label(p: Dict[str, Any]) -> str:
    """The most precise location the application itself established for a
    located passage: page and table from the extraction's own markers. A
    section is not given: the extracted text does not mark sections reliably."""
    if not p.get("source"):
        return "position not available (matched only after spacing was normalised)"
    location = p.get("location")
    if location:
        if p.get("in_table") and "table" not in location.lower():
            location += ", table text"
        return location
    return ("page not established (the extracted text has no page marker here; "
            "documents other than PDFs have none)")


def _excerpt(text: str) -> Tuple[str, bool]:
    text = " ".join((text or "").split())
    if len(text) <= EXCERPT_CHARS:
        return text, False
    cut = text[:EXCERPT_CHARS].rsplit(" ", 1)[0]
    return cut + " […]", True


def _role(p: Dict[str, Any]) -> str:
    role = p.get("role")
    if not role:
        return ""
    reading = {"supports": "supports", "qualifies": "qualifies", "contradicts": "contradicts"}.get(role, role)
    return f"; the AI reads it as one that {reading} the finding"


def _provenance(quote: str, intermediate: Optional[Sequence[Tuple[str, str]]]) -> str:
    """Where an unauthenticated quotation came from, only as far as the saved
    records show it. Never inferred beyond an exact (formatting-folded) match."""
    if intermediate is None:
        return ("Its origin cannot be established: the AI's intermediate text (file summaries and "
                "section notes) is saved only for reviews run in Development mode.")
    for label, text in intermediate:
        if text and ec.locate_span(quote, text):
            return (f"It appears verbatim in {label}, which is AI-generated text, but not in the "
                    "manuscript text.")
    return ("It is not in the manuscript text or in the saved intermediate AI text, so its origin "
            "cannot be established.")


def _card_evidence_lines(card: Dict[str, Any],
                         intermediate: Optional[Sequence[Tuple[str, str]]]) -> List[str]:
    """Fallback when the manuscript text was not saved: the Evidence Card's
    own results, labelled as such."""
    groups = card.get("evidence_groups") or {}
    located = [p for key in ("supporting", "qualifying", "other") for p in groups.get(key) or []]
    out: List[str] = []
    if located:
        out += ["**Manuscript passages located by the application** (verbatim; location shows "
                "where a passage is, not that the AI's reading of it is correct):", ""]
        for p in located:
            where = f"{_location_label(p)}" + (f" in {p['source']}" if p.get("source") else "")
            excerpt, cut = _excerpt(p.get("text", ""))
            out += [f"- {dr.md_text(where)} · {dr.md_text(p.get('origin') or 'origin not recorded')}"
                    f"{dr.md_text(_role(p))}"
                    + (" · excerpt; the full passage is on the Evidence Card" if cut else ""),
                    "", dr.md_quote(excerpt), ""]
    else:
        out += ["**Manuscript passages located by the application:** none. Check the manuscript "
                "directly; an unsuccessful match does not show that the information is absent.", ""]
    unverified = groups.get("unverified") or []
    if unverified:
        out += ["**Quotations that could not be authenticated** (not manuscript evidence):", ""]
        for p in unverified:
            reason = p.get("note") or "not found in the manuscript"
            detail = (f"Where it appears in the review record: {p.get('origin') or 'not recorded'}. "
                      f"Not authenticated: {reason}. {_provenance(p.get('text', ''), intermediate)}")
            if p.get("matches_item_text"):
                detail += " The quotation repeats the finding's own wording."
            detail += (" Uncertain: whether these words occur in the manuscript at all, and so "
                       "whether the finding rests on them.")
            out += ["- " + dr.md_text(detail), "", dr.md_quote(p.get("text", "")), ""]
    elif card.get("quotation_notice"):
        out += ["**Quotations that could not be authenticated:** the record notes one, but does "
                "not keep its wording; see the Evidence Card.", ""]
    return out


ITEM_ORIGIN = "quoted by the review item as its evidence"
VERIFIER_ORIGIN = "cited by the verifier"
_READING = {"supports": "supporting", "qualifies": "qualifying", "contradicts": "contradicting"}
CARD_FALLBACK_NOTE = (
    "The manuscript text was not saved with this review, so the quotations could not be re-checked "
    "here. The Evidence Card's results are shown instead. That check also ignores punctuation, "
    "including decimal points and signs, so it is less strict than the check described in section C.")


def _ai_quotations(card: Dict[str, Any]) -> List[Tuple[str, str, Optional[str], Optional[str]]]:
    """(quotation as the AI wrote it, origin, role, role basis), taken from the
    saved verification record behind the card, in the order the Evidence Card
    collects them. Older card snapshots without that record give the card's
    own passages."""
    prov = card.get("provenance") or {}
    out: List[Tuple[str, str, Optional[str], Optional[str]]] = []
    if "model_quote" in prov or "model_evidence" in prov:
        for q in ec._item_quotes(card.get("original", "")):
            out.append((q, ITEM_ORIGIN, None, None))
        evidence = prov.get("model_evidence") or []
        for e in evidence:
            if not isinstance(e, dict):
                continue
            role = e.get("role") if e.get("role") in ec.ROLE_NAMES else None
            out.append(((e.get("quote") or "").strip(), VERIFIER_ORIGIN, role,
                        "the verifier's reading" if role else None))
        main = (prov.get("model_quote") or "").strip()
        if main:
            role = None if evidence else ec.ROLE_FROM_VERDICT.get(prov.get("model_verdict") or "")
            out.append((main, VERIFIER_ORIGIN, role,
                        "inferred from the verifier's verdict" if role else None))
    else:
        for p in card.get("evidence") or []:
            out.append(((p.get("text") or "").strip(), p.get("origin") or "origin not recorded",
                        p.get("role"), p.get("role_basis")))
    return [q for q in out if q[0]]


def _cite_text(origin: str, role: Optional[str], basis: Optional[str]) -> str:
    if role not in _READING:
        return origin
    if basis and basis.startswith("inferred"):
        return f"{origin}, read as {_READING[role]} the finding (inferred from the verifier's verdict)"
    return f"{origin}, which reads it as {_READING[role]} the finding"


def _group(card: Dict[str, Any], manuscript: "qm.Manuscript", sources: Dict[str, str]) -> List[Dict[str, Any]]:
    """Classify each AI quotation and merge those that resolve to the same
    thing: the same manuscript span(s) for an exact match, the same quotation
    and line for a related passage, the same wording otherwise. Nothing else
    is merged; provenance from every merged quotation is kept."""
    entries: Dict[tuple, Dict[str, Any]] = {}
    for quote, origin, role, basis in _ai_quotations(card):
        result = qm.classify(quote, manuscript)
        entry = entries.setdefault(result.key, {"result": result, "cites": [], "quotes": [],
                                                 "card_located": False, "card_note": ""})
        cite = _cite_text(origin, role, basis)
        if role in _READING:
            # A role-bearing citation replaces the same origin's role-less one.
            entry["cites"] = [c for c in entry["cites"] if c != origin]
            if cite not in entry["cites"]:
                entry["cites"].append(cite)
        elif not any(c == origin or c.startswith(origin + ",") for c in entry["cites"]):
            entry["cites"].append(cite)
        qkey = tuple(t.text for t in qm.tokens(quote))
        if qkey not in entry.setdefault("quote_keys", []):
            entry["quote_keys"].append(qkey)
            entry["quotes"].append(quote)
        elif quote not in entry["quotes"]:
            entry["variants"] = True
        card_check = ec._passage(quote, sources)
        if card_check["status"] == "located":
            entry["card_located"] = True
        elif not entry["card_note"]:
            entry["card_note"] = card_check.get("note") or ""
    return list(entries.values())


def _where(loc: "qm.Location") -> str:
    return _location_label({"source": loc.source, "location": loc.location, "in_table": loc.in_table}) \
        + f" in {loc.source}"


def _related_excerpt(result: "qm.Result", manuscript: "qm.Manuscript") -> str:
    loc = result.locations[0]
    text = " ".join(loc.text.split())
    if len(text) <= EXCERPT_CHARS:
        return text
    body = manuscript.sources[loc.source]
    start, end = result.focus
    lo, hi = max(loc.start, start - 120), min(loc.end, end + 120)
    return (("[…] " if lo > loc.start else "") + " ".join(body[lo:hi].split())
            + (" […]" if hi < loc.end else ""))


def _card_difference(entry: Dict[str, Any]) -> str:
    state = entry["result"].state
    if entry["card_located"] and state != qm.EXACT:
        return ("The Evidence Card lists this quotation as located. Its check ignores all punctuation, "
                "including decimal points and signs, so it is less strict than the check used here; "
                "the stricter result is shown.")
    if not entry["card_located"] and state == qm.EXACT:
        reason = entry["card_note"] or "its check did not match it"
        return (f"The Evidence Card does not list this quotation as located ({reason}). Here it is "
                "authenticated because the passage occurs exactly once in the manuscript text.")
    return ""


def _evidence_lines(card: Optional[Dict[str, Any]],
                    intermediate: Optional[Sequence[Tuple[str, str]]],
                    manuscript: Optional["qm.Manuscript"] = None,
                    sources: Optional[Dict[str, str]] = None) -> List[str]:
    if card is None:
        return ["**Manuscript evidence:** No Evidence Card corresponds to this finding, so no "
                "evidence location is available for it.", ""]
    if manuscript is None:
        return ["*" + CARD_FALLBACK_NOTE + "*", ""] + _card_evidence_lines(card, intermediate)
    entries = _group(card, manuscript, sources or {})
    if not entries:
        return ["**Manuscript evidence:** the AI gave no quotation for this finding, so the application "
                "located no passage. Check the manuscript directly; this does not show that the "
                "information is absent.", ""]
    out: List[str] = []
    exact = [e for e in entries if e["result"].state == qm.EXACT]
    related = [e for e in entries if e["result"].state == qm.RELATED]
    missing = [e for e in entries if e["result"].state == qm.NOT_LOCATED]
    original = card.get("original", "")

    if exact:
        out += [f"**{qm.STATE_LABELS[qm.EXACT]}** (verbatim manuscript text; the location shows where "
                "it is, not that the AI's reading of it is correct):", ""]
    else:
        out += [f"**{qm.STATE_LABELS[qm.EXACT]}:** none.", ""]
    for e in exact:
        r = e["result"]
        first = r.locations[0]
        excerpt, cut = _excerpt(first.text)
        out += ["- " + dr.md_text(_where(first) + " · " + "; ".join(e["cites"]))
                + (" · excerpt; the full passage is on the Evidence Card" if cut else ""),
                "", dr.md_quote(excerpt), ""]
        notes = []
        notes.append("Matched after normalising: " + "; ".join(r.normalised) + "."
                     if r.normalised else "Matched exactly, apart from spacing and line breaks.")
        if r.occurrences > 1:
            others = [_where(loc) for loc in r.locations[1:]]
            more = r.occurrences - len(r.locations)
            notes.append(r.reason + " Also at: " + "; ".join(others)
                         + (f"; and {more} more" if more > 0 else "") + ".")
            notes.append("What to check: " + r.check)
        diff = _card_difference(e)
        if diff:
            notes.append(diff)
        for n in notes:
            out += [dr.md_text(n), ""]

    if related:
        out += [f"**{qm.STATE_LABELS[qm.RELATED]}** (the AI's quotation is not the manuscript's "
                "wording; the passage is shown so that you can compare them):", ""]
    for e in related:
        r = e["result"]
        out += ["- " + dr.md_text(_where(r.locations[0]) + " · " + "; ".join(e["cites"])), ""]
        for q in e["quotes"]:
            out += ["AI quotation (AI-written; not manuscript text):", "", dr.md_quote(q), ""]
        if e.get("variants"):
            out += ["Another citation gives the same quotation with different punctuation or spacing.", ""]
        out += ["Related manuscript passage (verbatim extracted text):", "",
                dr.md_quote(_related_excerpt(r, manuscript)), ""]
        if r.table_first_row:
            out += ["First row of the same table as extracted (usually its column headings; check "
                    "against the manuscript):", "", dr.md_quote(_excerpt(r.table_first_row)[0]), ""]
        if r.omitted:
            out += [dr.md_text("Manuscript text between the quoted parts, left out by the quotation: "
                               + " | ".join(f"“{o}”" for o in r.omitted) + "."), ""]
        out += [dr.md_text("Why not authenticated: " + r.reason), "",
                dr.md_text("What to check: " + r.check), ""]
        diff = _card_difference(e)
        if diff:
            out += [dr.md_text(diff), ""]

    if missing:
        out += [f"**{qm.STATE_LABELS[qm.NOT_LOCATED]}** (not manuscript evidence):", ""]
    for e in missing:
        r = e["result"]
        out += ["- " + dr.md_text("Where it appears in the review record: " + "; ".join(e["cites"]) + "."), ""]
        for q in e["quotes"]:
            out += [dr.md_quote(q), ""]
        if e.get("variants"):
            out += ["Another citation gives the same quotation with different punctuation or spacing.", ""]
        detail = "Why not located: " + r.reason + " " + _provenance(r.quote, intermediate)
        if any(ec.matches_item_text(q, original) for q in e["quotes"]):
            detail += " The quotation repeats the finding's own wording."
        out += [dr.md_text(detail), ""]
        if r.check:
            out += [dr.md_text("What to check: " + r.check), ""]
        diff = _card_difference(e)
        if diff:
            out += [dr.md_text(diff), ""]
    return out


def _observation_summary(candidate_accounting: Optional[dict]) -> List[str]:
    out = ["## B. Additional observations from the initial reading (not independently verified)", ""]
    if not isinstance(candidate_accounting, dict) or "records" not in candidate_accounting:
        out.append("No record of initial-reading observations was saved with this review.")
        return out + [""]
    records = candidate_accounting.get("records") or []
    missing = [r for r in records if r.get("status") == "not_carried_forward"]
    if not missing:
        out.append("Every observation from the initial reading has a wording match in the final "
                   "appraisal.")
        return out + [""]
    out.append(f"{len(missing)} observation(s) from the section-by-section reading share too little "
               "wording with the final appraisal to be matched to it. Matching is by shared words "
               "only, so some may be covered in the appraisal in different words. They are "
               "AI-generated, have not been checked against the manuscript, and are not findings. "
               "The full list is kept in the original appendix and the verification record.")
    return out + [""]


STATUS_KEY = [
    "## C. What the evidence statuses mean",
    "",
    "- **AI-generated observation:** anything written by the model, including every finding here.",
    "- **Final appraisal finding (C, Q):** included in the final appraisal. Still AI-generated and "
    "provisional; your evaluation decides whether it stands.",
    "- **Evidence as stated in the appraisal:** what the AI wrote as its evidence. It is not "
    "manuscript evidence unless a passage is also listed as authenticated.",
    "- **Exact quotation authenticated:** the AI's quotation occurs in the extracted manuscript text "
    "as one continuous passage. Only spacing, line breaks, letter case, Unicode compatibility forms, "
    "quotation-mark and dash styles, and the punctuation , ; : ' \" ( ) [ ] { } | (and full stops "
    "outside numbers) are disregarded, and each entry says which of these the match relied on. "
    "Signs, digits, decimal places, units, group labels and symbols such as ± < > = % must agree "
    "exactly. This establishes location only, not that the AI's interpretation is correct.",
    "- **Related manuscript passage located — quotation not authenticated:** every word, number "
    "and symbol of the AI's quotation occurs in the same order on one line of the manuscript (for "
    "example, one table row), but with other text between them, which is shown. Only one line in "
    "the manuscript may qualify. The AI's quotation is not the manuscript's wording, and the "
    "passage is not evidence that the AI's statistical interpretation is correct.",
    "- **Quotation not located — not authenticated:** no reliable location was found. This does not "
    "show that the manuscript lacks the information; where the saved records allow, the "
    "quotation's origin is stated.",
    "- **Duplicates:** a passage cited more than once for the same finding is shown once, with "
    "every citation listed. Passages at different places are never merged.",
    "- **Disputed:** the AI verifier disputed the finding. That does not settle the finding.",
    "- **Initial-reading observation:** noted early in the reading but not included in the final "
    "appraisal; unverified.",
    "",
]


def _ai_text(text: Any) -> str:
    """AI-written appraisal text, kept as the Markdown it was written in (bold
    labels such as "**Reason:**" then render as formatting). Line breaks are
    joined so the text cannot start a heading or block of its own; HTML is
    escaped by the renderer, never interpreted."""
    return " ".join(str(text or "").split())


def render(report_text: str, links: Optional[Dict[str, Any]],
           card_set: Optional[Dict[str, Any]], candidate_accounting: Optional[dict],
           generated_at: Optional[str] = None,
           intermediate: Optional[Sequence[Tuple[str, str]]] = None,
           sources: Optional[Dict[str, str]] = None) -> str:
    """The concise appendix. links is review_links.build_links() output, used
    only to find the Evidence Card behind each appendix entry. intermediate is
    the saved AI-generated intermediate text, as (label, text) pairs, or None
    when the review did not keep it. sources is the saved manuscript text the
    verifier saw ({name: text}); each AI quotation is checked against it
    (quote_match). Without it, the Evidence Cards' own results are shown."""
    sources = {k: v for k, v in (sources or {}).items() if isinstance(v, str) and v.strip()}
    manuscript = qm.Manuscript(sources) if sources else None
    cards = {c.get("label"): c for c in (card_set or {}).get("cards") or []}
    by_appendix: Dict[str, Optional[Dict[str, Any]]] = {}
    for f in (links or {}).get("findings") or []:
        if f.get("appendix_id") and f.get("id"):
            by_appendix[f["appendix_id"]] = cards.get(f["id"])

    when = f" on {generated_at}" if generated_at else ""
    out = ["# Human Evidence Appendix", "",
           "*" + PRESENTATION_NOTE.format(when=when) + "*", "",
           "This appendix helps you evaluate the concerns and verification questions in the final "
           "appraisal. Strengths are covered by the Evidence Cards. Every item is AI-generated and "
           "provisional; you remain responsible for deciding whether it is justified.", "",
           "## A. Final appraisal findings", ""]

    findings = hea.extract_final_findings(report_text or "")
    details = hea._extract_finding_details(report_text or "")
    if not findings:
        out += ["The final appraisal contains no concerns or verification questions.", ""]
    for finding in findings:
        fid = finding["finding_id"]
        concern = finding["review_status"] == "concern"
        kind = "Concern" if concern else "Verification question"
        card = by_appendix.get(fid)
        detail = details.get(fid) or {}
        out += [f"## {fid} — {kind}", "",
                "**Finding (final appraisal, AI-generated):** " + _ai_text(finding["text"]), ""]
        if detail.get("reported_evidence"):
            out += ["**Evidence as stated in the appraisal** (AI-written; may come from the AI's "
                    "summary rather than the manuscript): " + _ai_text(detail["reported_evidence"]), ""]
        if detail.get("interpretation"):
            label = "Why it matters" if concern else "Reason"
            out += [f"**{label} (AI-written):** " + _ai_text(detail["interpretation"]), ""]
        out += _evidence_lines(card, intermediate, manuscript, sources)
        quals = _qualifications(card)
        if quals:
            out.append("**Qualifications:**")
            out.append("")
            out += ["- " + dr.md_text(q) for q in quals]
            out.append("")
    out += _observation_summary(candidate_accounting)
    out += STATUS_KEY
    return "\n".join(out).rstrip() + "\n"
